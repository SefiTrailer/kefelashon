// Tags to REMOVE (bad, too generic when used alone)
const REMOVE_TAGS = new Set(['ביטוי', 'בית', 'חיה', 'פתגם', 'משל', 'שמיעתי', 'מטבע לשון', 'כפל לשון', 'עיצבון', 'חכמה', 'תעודה', 'שיח מכבד']);

// Tags to REPLACE
const REPLACE_TAGS = {
  'בית ספר': 'חינוך',
  'חיות ומשקאות': 'חיות',
  'שילוב של חיות': 'חיות',
  'בעלי חיים': 'חיות',
  'עופות': 'עופות',
  'דגים': 'דגים',
  'סוסים': 'סוסים',
};

function getTagsFromText(text) {
  if (!text) return [];
  const lower = text.toLowerCase();
  const added = new Set();
  RULES.forEach(rule => {
    if (rule.keywords.some(kw => lower.includes(kw.toLowerCase()))) {
      rule.tags.forEach(t => added.add(t));
    }
  });
  return [...added];
}

let changed = 0;
let stats = { categoriesAdded: 0, tagsRemoved: 0, tagsReplaced: 0 };

for (const [filename, meta] of Object.entries(data)) {
  const text = `${filename} ${meta.title || ''} ${meta.explanation || ''}`;
  const existingTags = new Set((meta.topic || '').split(',').map(t => t.trim()).filter(Boolean));
  
  // Build new tag set
  let newTags = new Set();
  
  // Keep existing tags, but remove bad ones and apply replacements
  for (const tag of existingTags) {
    if (REMOVE_TAGS.has(tag)) {
      stats.tagsRemoved++;
      continue; // Don't carry over
    }
    if (REPLACE_TAGS[tag]) {
      newTags.add(REPLACE_TAGS[tag]);
      stats.tagsReplaced++;
    } else {
      newTags.add(tag);
    }
  }
  
  // Add tags from keyword analysis
  const suggested = getTagsFromText(text);
  let addedAny = false;
  for (const t of suggested) {
    if (!newTags.has(t)) {
      newTags.add(t);
      addedAny = true;
      stats.categoriesAdded++;
    }
  }

  const newTopicStr = [...newTags].join(', ');
  if (newTopicStr !== (meta.topic || '')) {
    data[filename].topic = newTopicStr;
    changed++;
  }
}

fs.writeFileSync('./data.json', JSON.stringify(data, null, 2), 'utf-8');
console.log(`\nDone! Updated ${changed} images.`);
console.log(`Stats:`, stats);
